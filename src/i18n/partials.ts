// Sample UI translations for North-East languages.
// These are illustrative for the prototype — full translations would be added
// by native speakers. Any missing key falls back to English automatically.
// as=Assamese, bn=Bengali, mni=Manipuri/Meitei, kha=Khasi, miz=Mizo, grt=Garo, trp=Tripuri

// Keys shared across the seven sample languages below. Each entry can override
// the English fallback for the most user-facing strings (navigation, actions,
// the daily routine game, reminders and voice commands).
type PartialDict = Record<string, string>;

function partial(
  brandTagline: string,
  landmark: Record<string, string>, // nav + landing
  common: Record<string, string>,
  games: Record<string, string>,
  routine: Record<string, string>,
  voice: Record<string, string>,
  home: Record<string, string>,
): PartialDict {
  return {
    'brand.tagline': brandTagline,
    ...landmark,
    ...common,
    'nav.home': common['common.home'] ?? landmark['nav.home'],
    'nav.games': landmark['nav.games'],
    'common.back': common['common.back'],
    'common.done': common['common.done'],
    'games.complete': games['games.complete'],
    'games.home': games['games.home'],
    'games.leave.confirm': common['games.leave.confirm'],
    'games.leave.body': common['games.leave.body'],
    'games.leave.continue': common['games.leave.continue'],
    'games.leave.leave': common['games.leave.leave'],
    ...games,
    ...routine,
    ...voice,
    ...home,
  };
}

